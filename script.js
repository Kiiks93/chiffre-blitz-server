function getFlagEmoji(flag) {
    if (!flag) return '🇫🇷';
    let cleanFlag = flag.replace(/['"]/g, '').trim();
    if (cleanFlag.length === 2) {
        try {
            const codePoints = cleanFlag.toUpperCase().split('').map(char => 127397 + char.charCodeAt(0));
            return String.fromCodePoint(...codePoints);
        } catch(e) {
            return '🇫🇷';
        }
    }
    return cleanFlag;
}

