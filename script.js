function applyTranslations() {
    const dict = i18n[currentLang];
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.innerText = dict[key];
        }
    });
    document.getElementById('lang-btn').innerText = (currentLang === 'fr') ? 'ENG' : 'FR';
}

const SoundEngine = {
    ctx: null, isMuted: false, timerId: null, currentMode: null, step: 0, bpm: 105,
    init() { 
        try {
            if (!this.ctx) { 
                const AudioCtx = window.AudioContext || window.webkitAudioContext;
                this.ctx = new AudioCtx(); 
            }
            if (this.ctx.state === 'suspended') {
                this.ctx.resume();
            }
        } catch(e) {}
    },
    toggleMute() {
        this.isMuted = !this.isMuted;
        if (this.isMuted) this.stopMusic(false);
        else if (this.currentMode) this.startMusic(this.currentMode);
        return this.isMuted;
    },
    playClick() {
        if (this.isMuted) return; this.init();
        if (!this.ctx) return;
        const t = this.ctx.currentTime;
        const osc = this.ctx.createOscillator(), gain = this.ctx.createGain();
        osc.type = 'triangle';
        osc.frequency.setValueAtTime(440, t);
        osc.frequency.exponentialRampToValueAtTime(880, t + 0.06);
        gain.gain.setValueAtTime(0.1, t);
        gain.gain.exponentialRampToValueAtTime(0.0001, t + 0.06);
        osc.connect(gain); gain.connect(this.ctx.destination);
        osc.start(t); osc.stop(t + 0.06);
    },
    playError() {
        if (this.isMuted) return; this.init();
        if (!this.ctx) return;
        const t = this.ctx.currentTime;
        const osc = this.ctx.createOscillator(), gain = this.ctx.createGain();
        osc.type = 'sawtooth';
        osc.frequency.setValueAtTime(150, t);
        osc.frequency.linearRampToValueAtTime(80, t + 0.1);
        gain.gain.setValueAtTime(0.1, t);
        gain.gain.exponentialRampToValueAtTime(0.0001, t + 0.1);
        osc.connect(gain); gain.connect(this.ctx.destination);
        osc.start(t); osc.stop(t + 0.1);
    },
    playVictory() {
        if (this.isMuted) return; this.init();
        if (!this.ctx) return;
        [523.25, 659.25, 783.99, 1046.50].forEach((freq, i) => {
            setTimeout(() => {
                if (this.isMuted || !this.ctx) return;
                const t = this.ctx.currentTime;
                const osc = this.ctx.createOscillator(), gain = this.ctx.createGain();
                osc.type = 'square';
                osc.frequency.setValueAtTime(freq, t);
                gain.gain.setValueAtTime(0.08, t);
                gain.gain.exponentialRampToValueAtTime(0.0001, t + 0.25);
                osc.connect(gain); gain.connect(this.ctx.destination);
                osc.start(t); osc.stop(t + 0.25);
            }, i * 120);
        });
    },
    stopMusic(clear = true) {
        if (this.timerId) clearInterval(this.timerId);
        this.timerId = null;
        if (clear) this.currentMode = null;
    },
    startMusic(mode) {
        if (this.isMuted) return;
        this.init();
        if (this.ctx && this.ctx.state === 'suspended') {
            this.ctx.resume();
        }
        if (this.timerId && this.currentMode === mode) {
            return;
        }
        this.stopMusic(false);
        this.currentMode = mode;
        this.step = 0;

        this.bpm = (mode === 'menu') ? 95 : 105;
        const intervalMs = (60 / this.bpm / 4) * 1000;

        this.timerId = setInterval(() => {
            if (this.isMuted || !this.ctx || this.ctx.state !== 'running') return;
            this.tickSequence(this.currentMode, this.step);
            this.step = (this.step + 1) % 64;
        }, intervalMs);
    },
    tickSequence(mode, step) {
        if (!this.ctx) return;
        const t = this.ctx.currentTime;
        const scale = [110, 123.47, 130.81, 146.83, 164.81, 196, 220, 246.94, 261.63, 293.66, 329.63, 349.23, 392];

        if (step % 4 === 0) {
            const osc = this.ctx.createOscillator();
            const gain = this.ctx.createGain();
            osc.type = 'sine';
            osc.frequency.setValueAtTime(mode === 'menu' ? 110 : 130, t);
            osc.frequency.exponentialRampToValueAtTime(30, t + 0.08);
            gain.gain.setValueAtTime(0.18, t);
            gain.gain.exponentialRampToValueAtTime(0.0001, t + 0.09);
            osc.connect(gain); gain.connect(this.ctx.destination);
            osc.start(t); osc.stop(t + 0.09);
        }

        if (step === 4 || step === 12 || step === 20 || step === 28 || step === 36 || step === 44 || step === 52 || step === 60) {
            const bufferSize = this.ctx.sampleRate * 0.07;
            const buffer = this.ctx.createBuffer(1, bufferSize, this.ctx.sampleRate);
            const data = buffer.getChannelData(0);
            for (let i = 0; i < bufferSize; i++) data[i] = Math.random() * 2 - 1;
            const noise = this.ctx.createBufferSource();
            noise.buffer = buffer;
            const filter = this.ctx.createBiquadFilter();
            filter.type = 'highpass'; filter.frequency.setValueAtTime(1400, t);
            const gain = this.ctx.createGain();
            gain.gain.setValueAtTime(0.1, t);
            gain.gain.exponentialRampToValueAtTime(0.0001, t + 0.07);
            noise.connect(filter); filter.connect(gain); gain.connect(this.ctx.destination);
            noise.start(t);
        }

        if (step % 2 === 1 && mode !== 'menu') {
            const bufferSize = this.ctx.sampleRate * 0.03;
            const buffer = this.ctx.createBuffer(1, bufferSize, this.ctx.sampleRate);
            const data = buffer.getChannelData(0);
            for (let i = 0; i < bufferSize; i++) data[i] = Math.random() * 2 - 1;
            const noise = this.ctx.createBufferSource();
            noise.buffer = buffer;
            const filter = this.ctx.createBiquadFilter();
            filter.type = 'highpass'; filter.frequency.setValueAtTime(6000, t);
            const gain = this.ctx.createGain();
            gain.gain.setValueAtTime(0.03, t);
            gain.gain.exponentialRampToValueAtTime(0.0001, t + 0.03);
            noise.connect(filter); filter.connect(gain); gain.connect(this.ctx.destination);
            noise.start(t);
        }

        if (mode !== 'menu') {
            const bar = Math.floor(step / 16);
            let melodyPatterns = [
                [0, 2, 4, 7, 9, 7, 4, 2, 3, 5, 7, 10, 9, 7, 5, 2],
                [2, 4, 5, 9, 11, 9, 5, 4, 5, 7, 9, 12, 11, 9, 7, 4],
                [4, 5, 7, 11, 12, 11, 7, 5, 7, 9, 11, 14, 12, 11, 9, 7],
                [7, 9, 11, 14, 16, 14, 11, 9, 11, 12, 14, 16, 14, 12, 9, 4]
            ];
            const currentPattern = melodyPatterns[bar];
            const noteIdx = currentPattern[step % 16];
            const freq = scale[noteIdx % scale.length] * 2;

            const osc = this.ctx.createOscillator();
            const gain = this.ctx.createGain();
            const filter = this.ctx.createBiquadFilter();

            osc.type = (step % 4 === 0) ? 'sawtooth' : 'square';
            osc.frequency.setValueAtTime(freq, t);

            filter.type = 'lowpass';
            filter.frequency.setValueAtTime(1800 + (bar * 200), t);

            gain.gain.setValueAtTime(0.04, t);
            gain.gain.exponentialRampToValueAtTime(0.0001, t + 0.09);

            osc.connect(filter); filter.connect(gain); gain.connect(this.ctx.destination);
            osc.start(t); osc.stop(t + 0.09);
        } else {
            if (step % 2 === 0) {
                const menuBar = Math.floor(step / 16);
                const menuPatterns = [
                    [0, 3, 5, 7],
                    [2, 5, 7, 9],
                    [3, 7, 8, 10],
                    [5, 8, 10, 12]
                ];
                const chord = menuPatterns[menuBar];
                const freq = scale[chord[(step / 2) % chord.length]];
                
                const osc = this.ctx.createOscillator();
                const gain = this.ctx.createGain();
                osc.type = 'square';
                osc.frequency.setValueAtTime(freq, t);
                gain.gain.setValueAtTime(0.025, t);
                gain.gain.exponentialRampToValueAtTime(0.0001, t + 0.15);
                osc.connect(gain); gain.connect(this.ctx.destination);
                osc.start(t); osc.stop(t + 0.15);
            }
        }
    }
};

